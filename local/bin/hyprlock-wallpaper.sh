#!/bin/bash
# Writes the current wallpaper's path where hyprlock can read it.
#
# hyprlock has no way to read a path out of a file, so the wallpaper has to
# arrive as a hyprlang variable. wallpaper-switch.sh calls this right after
# matugen, so colors.conf and wallpaper.conf are always regenerated together
# and can never disagree about which wallpaper is current.
#
# Was generate-hyprlock-colors.sh, which derived a single $accent from
# matugen's colors.json. matugen now writes the whole hyprlock palette itself
# (see ~/.config/matugen/templates/hyprlock-colors.conf.template), so the only
# thing left to generate is the path.
LAST="$HOME/.config/hypr/last-wallpaper.txt"
OUT="$HOME/.config/hyprlock/wallpaper.conf"

mkdir -p "$(dirname "$OUT")"

wall=""
[ -f "$LAST" ] && wall="$(cat "$LAST")"

# shellcheck disable=SC2016  # "$wall" here is a hyprlang variable name in the
# generated file, not a shell expansion - the single quotes are deliberate.
if [ -n "$wall" ] && [ -f "$wall" ]; then
  printf '# Generated by hyprlock-wallpaper.sh — DO NOT EDIT BY HAND.\n$wall = %s\n' "$wall" > "$OUT"
else
  # No wallpaper recorded yet, or it has been deleted. `screenshot` is
  # hyprlock's built-in: it grabs the screen as it locks, which the layouts
  # then blur. Better than a missing file, which renders as black.
  printf '# Generated by hyprlock-wallpaper.sh — no wallpaper on record.\n$wall = screenshot\n' > "$OUT"
fi
